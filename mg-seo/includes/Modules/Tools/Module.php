<?php
/**
 * Tools module: robots.txt, llms.txt, IndexNow, settings transfer and housekeeping.
 *
 * @package MGSEO
 */

namespace MGSEO\Modules\Tools;

use MGSEO\Module as Base;

defined( 'ABSPATH' ) || exit;

/**
 * Settings and small utilities.
 */
final class Module extends Base {

	/**
	 * Module id.
	 */
	public function id(): string {
		return 'tools';
	}

	/**
	 * Register hooks.
	 */
	public function boot(): void {
		add_action( 'init', array( self::class, 'ensure_cron' ) );
		Robots::boot();
		Llms::boot();
		IndexNow::boot();
		if ( is_admin() ) {
			Utilities::boot();
		}
	}

	/**
	 * Schedule the shared daily housekeeping event other modules hook into.
	 */
	public static function ensure_cron(): void {
		if ( ! wp_next_scheduled( 'mgseo_daily' ) ) {
			wp_schedule_event( time() + HOUR_IN_SECONDS, 'daily', 'mgseo_daily' );
		}
	}

	/**
	 * Public post types for multichecks.
	 *
	 * @return array<string, string>
	 */
	private static function post_type_options(): array {
		$options = array();
		foreach ( get_post_types( array( 'public' => true ), 'objects' ) as $object ) {
			if ( 'attachment' === $object->name ) {
				continue;
			}
			$options[ $object->name ] = (string) $object->labels->name;
		}
		return $options;
	}

	/**
	 * Settings schema.
	 */
	public function settings_menu_title(): string {
		return __( 'Tools settings', 'mg-seo' );
	}

