	/**
	 * Utilities page.
	 */
	public function admin_pages(): array {
		return array(
			array(
				'slug'       => Utilities::PAGE,
				'title'      => __( 'SEO Utilities', 'mg-seo' ),
				'menu_title' => __( 'Utilities', 'mg-seo' ),
				'capability' => 'mgseo_manage_settings',
				'callback'   => array( Utilities::class, 'render' ),
				'position'   => 90,
			),
		);
	}

	/**
	 * Activation: schedule housekeeping.
	 */
	public function activate(): void {
		self::ensure_cron();
	}

	/**
	 * Remove data.
	 */
	public function uninstall(): void {
		delete_option( IndexNow::LOG );
		delete_transient( IndexNow::RECENT );
		delete_transient( Llms::CACHE );
		wp_clear_scheduled_hook( 'mgseo_daily' );
	}
}
